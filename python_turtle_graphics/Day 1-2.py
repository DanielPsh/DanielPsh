#박상현
import turtle as t
t.shape("turtle")
t.speed(0)

t.up()
t.fd(100)
t.down()

t.color("red")
t.begin_fill()
t.circle(50)
t.end_fill()

t.up()
t.goto(-100,0)
t.down()

t.color("orange")
t.begin_fill()
t.circle(50)
t.end_fill()
t.up()
t.goto(0,100)
t.down()

t.color("yellow")
t.begin_fill()
t.fd(50)
t.left(90)
t.fd(100)
t.left(90)
t.fd(100)
t.left(90)
t.fd(100)
t.left(90)
t.end_fill()
t.up()

t.goto(0,-100)
t.down()
t.color("green")
t.begin_fill()
t.fd(50)
t.left(120)
t.fd(100)
t.left(120)
t.fd(100)
t.left(120)
t.fd(100)
t.end_fill()
